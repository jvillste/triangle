(ns triangle.wgpu
  "WebGPU for the triangle demo, on the full wgpu-native bindings that
  jextract generated from webgpu.h plus the wgpu-native extensions in
  wgpu.h (wgpu-native 22.1.0.5): package wgpu under java/, made and
  regenerated by regenerate-bindings.sh.

  This namespace is the demo half of the interop: the struct builders
  for the descriptors the demo fills, the two WGSL shaders, the vertex
  data conversion and the per-frame helpers. Each C struct is allocated
  with the layout jextract derived from the header (StructName/allocate)
  and filled through the generated per-field setters, so the byte
  layout cannot drift from the header. Unset members stay zero, which
  is what the C API expects for them: NULL pointers, zero counts, and
  the default enum values that live at 0.

  Handles cross the FFM boundary as opaque values: either a raw long
  address or a MemorySegment; ffi/pointer wraps both. The native
  library must be loaded first with triangle.ffi/load-libraries!,
  which also hands the bindings their symbol lookup."
  (:require [clojure.test :refer [deftest is testing]]
            [triangle.ffi :as ffi])
  (:import [java.lang.foreign Arena MemorySegment]
           [wgpu WGPUBufferDescriptor WGPUChainedStruct WGPUColor
            WGPUFragmentState WGPUMultisampleState WGPUPrimitiveState
            WGPURenderPassColorAttachment WGPURenderPassDescriptor
            WGPURenderPipelineDescriptor WGPUSurfaceConfiguration
            WGPUSurfaceDescriptor WGPUSurfaceDescriptorFromMetalLayer
            WGPUSurfaceDescriptorFromWaylandSurface
            WGPUSurfaceDescriptorFromWindowsHWND
            WGPUSurfaceDescriptorFromXlibWindow WGPUSurfaceTexture
            WGPUShaderModuleDescriptor WGPUShaderModuleWGSLDescriptor
            WGPUVertexAttribute WGPUVertexBufferLayout WGPUVertexState
            WGPUColorTargetState wgpu_h]))

;; ── enum values (webgpu.h)
;;
;; jextract renders each enum constant as a zero-argument static
;; getter on wgpu_h, which Clojure would read as a field, so they are
;; pulled through reflection once and bound under descriptive names.

(defn- wgpu-constant
  "A wgpu_h enum constant, by the header's spelling."
  [name]
  (let [method (first (filter #(= (.getName %) name)
                              (.getMethods (Class/forName "wgpu.wgpu_h"))))]
    (when-not method
      (throw (ex-info (str "no enum constant named " name " in the generated bindings")
                      {:constant name})))
    (int (.invoke method nil (into-array Object ())))))

