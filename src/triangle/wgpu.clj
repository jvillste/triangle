;; ── the WGSL triangle shader
;;
;; No vertex buffers: clip-space positions and per-corner colors are
;; computed from the builtin vertex index. The fragment stage receives
;; the (hardware-interpolated) corner colors and forwards them.

(def triangle-wgsl
  "struct VertexOut {
  @builtin(position) position: vec4<f32>,
  @location(0) color: vec3<f32>,
}

@vertex
fn vertex_main(@builtin(vertex_index) vertex_index: u32) -> VertexOut {
  var out: VertexOut;
  if (vertex_index == 0u) {
    out.position = vec4<f32>(0.0, 0.5, 0.0, 1.0);
    out.color = vec3<f32>(1.0, 0.0, 0.0);
  } else if (vertex_index == 1u) {
    out.position = vec4<f32>(-0.5, -0.25, 0.0, 1.0);
    out.color = vec3<f32>(0.0, 1.0, 0.0);
  } else {
    out.position = vec4<f32>(0.5, -0.25, 0.0, 1.0);
    out.color = vec3<f32>(0.0, 0.0, 1.0);
  }
  return out;
}

@fragment
fn fragment_main(input: VertexOut) -> @location(0) vec4<f32> {
  return vec4<f32>(input.color, 1.0);
}")
(def data-triangle-wgsl
  "struct DataOut {
  @builtin(position) position: vec4<f32>,
  @location(0) color: vec4<f32>,
}

@vertex
fn vertex_data_main(@location(0) position: vec2<f32>,
                    @location(1) color: vec4<f32>) -> DataOut {
  var out: DataOut;
  out.position = vec4<f32>(position, 0.0, 1.0);
  out.color = color;
  return out;
}

@fragment
fn fragment_data_main(input: DataOut) -> @location(0) vec4<f32> {
  return input.color;
}")

;; ── instance, adapter, device

(def ^:private null MemorySegment/NULL)

(defn create-instance!
  "Create the WebGPU instance (the default instance descriptor)."
  []
  (wgpu_h/wgpuCreateInstance null))

(defn first-adapter!
  "Enumerate the instance's adapters (a wgpu-native extension call, not
  core WebGPU) and return the first handle."
  [instance]
  (let [count (wgpu_h/wgpuInstanceEnumerateAdapters (ffi/pointer instance) null null)
        count (long count)]
    (when (zero? count)
      (throw (ex-info "WebGPU enumerated no adapters (missing or headless GPU driver?)"
                      {:adapter-count count})))
    (let [adapters (ffi/pointer-array! (int (min 8 count)))]
      (wgpu_h/wgpuInstanceEnumerateAdapters (ffi/pointer instance) null adapters)
      (let [adapter (ffi/deref-pointer adapters 0)]
        (when-not adapter
          (throw (ex-info "the second wgpuInstanceEnumerateAdapters call filled no slot" {})))
        adapter))))

(defn request-device!
  "Request a device on an adapter. The request is asynchronous: the
  callback resolves a promise, and we wait up to about two seconds for
  it. wgpu-native's processEvents is an unimplemented!() trap under
  X11 (a non-unwinding Rust abort), so we never call it."
  [adapter]
  (let [device-request (promise)
        callback (reify wgpu.WGPUAdapterRequestDeviceCallback$Function
                   (apply [_this status device _message _userdata]
                     (deliver device-request {:status (long status)
                                              :device device})))
        _ (wgpu_h/wgpuAdapterRequestDevice (ffi/pointer adapter) null
                                           (wgpu.WGPUAdapterRequestDeviceCallback/allocate
                                            callback (Arena/global))
                                           null)
        settled (loop [spins (int 0)]
                  (if (or (realized? device-request) (>= spins 1250))
                    (when (realized? device-request) @device-request)
                    (do (Thread/sleep 2)
                        (recur (inc spins)))))]
    (cond
      (nil? settled) (throw (ex-info
                             "device request timed out (no GPU driver to answer?)" {}))
      (not= 0 (:status settled)) (throw (ex-info
                                         (str "wgpuAdapterRequestDevice failed, status "
                                              (:status settled) " (0 means Success)")
                                         {:status (:status settled)}))
      :else (:device settled))))

(defn get-queue
  "wgpuDeviceGetQueue: the queue every submission goes through."
  [device]
  (wgpu_h/wgpuDeviceGetQueue (ffi/pointer device)))

;; ── surfaces

(defn- chain!
  "A WGPUChainedStruct with next = NULL and the given sType tag."
  [s-type]
  (doto (WGPUChainedStruct/allocate (Arena/global))
    (WGPUChainedStruct/sType (int s-type))))

(defn platform-descriptor!
  "Build the per-platform surface struct that chains into
  WGPUSurfaceDescriptor.nextInChain. kind is one of :x11, :wayland,
  :windows or :cocoa; members are that struct's pointer members in
  struct order: display and window for X11, Win32 and Wayland, the
  CAMetalLayer for Cocoa."
  [kind members]
  (case kind
    :cocoa (doto (WGPUSurfaceDescriptorFromMetalLayer/allocate (Arena/global))
             (WGPUSurfaceDescriptorFromMetalLayer/chain
              (chain! (surface-descriptor-s-type :cocoa)))
             (WGPUSurfaceDescriptorFromMetalLayer/layer (ffi/pointer (first members))))
    :windows (doto (WGPUSurfaceDescriptorFromWindowsHWND/allocate (Arena/global))
               (WGPUSurfaceDescriptorFromWindowsHWND/chain
                (chain! (surface-descriptor-s-type :windows)))
               (WGPUSurfaceDescriptorFromWindowsHWND/hinstance (ffi/pointer (first members)))
               (WGPUSurfaceDescriptorFromWindowsHWND/hwnd (ffi/pointer (second members))))
    :x11 (doto (WGPUSurfaceDescriptorFromXlibWindow/allocate (Arena/global))
            (WGPUSurfaceDescriptorFromXlibWindow/chain
             (chain! (surface-descriptor-s-type :x11)))
            (WGPUSurfaceDescriptorFromXlibWindow/display (ffi/pointer (first members)))
            (WGPUSurfaceDescriptorFromXlibWindow/window (long (second members))))
    :wayland (doto (WGPUSurfaceDescriptorFromWaylandSurface/allocate (Arena/global))
                (WGPUSurfaceDescriptorFromWaylandSurface/chain
                 (chain! (surface-descriptor-s-type :wayland)))
                (WGPUSurfaceDescriptorFromWaylandSurface/display (ffi/pointer (first members)))
                (WGPUSurfaceDescriptorFromWaylandSurface/surface (ffi/pointer (second members))))))

(defn surface-descriptor!
  "Build a WGPUSurfaceDescriptor chaining platform-descriptor."
  [platform-descriptor]
  (doto (WGPUSurfaceDescriptor/allocate (Arena/global))
    (WGPUSurfaceDescriptor/nextInChain (ffi/pointer platform-descriptor))))

(defn create-surface!
  "wgpuInstanceCreateSurface with the platform's chained descriptor:
  platform is a GLFW platform keyword, members the pointers of its
  struct (see platform-descriptor!). On X11 the window is an XID
  passed by value (not a Window*), so it travels as a raw long."
  [instance platform members]
  (wgpu_h/wgpuInstanceCreateSurface (ffi/pointer instance)
                                    (surface-descriptor! (platform-descriptor! platform members))))

(defn surface-configuration!
  "Build a WGPUSurfaceConfiguration for a surface of the given pixel
  size: default B8G8R8A8UnormSrgb format, render-target plus copy
  usage, FIFO present mode."
  [device width height]
  (doto (WGPUSurfaceConfiguration/allocate (Arena/global))
    (WGPUSurfaceConfiguration/device (ffi/pointer device))
    (WGPUSurfaceConfiguration/format bgra8-unorm-srgb)
    (WGPUSurfaceConfiguration/usage render-attachment-usage)
    (WGPUSurfaceConfiguration/width (int width))
    (WGPUSurfaceConfiguration/height (int height))
    (WGPUSurfaceConfiguration/presentMode (wgpu-constant "WGPUPresentMode_Fifo"))))

(defn configure-surface!
  "wgpuSurfaceConfigure with surface-configuration!."
  [surface device width height]
  (wgpu_h/wgpuSurfaceConfigure (ffi/pointer surface)
                               (surface-configuration! device width height)))

;; ── shaders, pipelines

(defn shader-module-descriptor!
  "Build a WGPUShaderModuleDescriptor chaining a
  WGPUShaderModuleWGSLDescriptor that names the WGSL source."
  [wgsl-source]
  (doto (WGPUShaderModuleDescriptor/allocate (Arena/global))
    (WGPUShaderModuleDescriptor/nextInChain
     (doto (WGPUShaderModuleWGSLDescriptor/allocate (Arena/global))
         (WGPUShaderModuleWGSLDescriptor/chain
          (chain! shader-module-s-type))
         (WGPUShaderModuleWGSLDescriptor/code (ffi/string! wgsl-source))))))

(defn create-shader-module!
  "Compile the given WGSL source into a shader module on a device."
  [device wgsl-source]
  (wgpu_h/wgpuDeviceCreateShaderModule (ffi/pointer device)
                                       (shader-module-descriptor! wgsl-source)))

(defn color-target-state!
  "Build a WGPUColorTargetState: one colour attachment target, default
  B8G8R8A8UnormSrgb format, default blending, writeMask = All."
  []
  (doto (WGPUColorTargetState/allocate (Arena/global))
    (WGPUColorTargetState/format bgra8-unorm-srgb)
    (WGPUColorTargetState/writeMask (wgpu-constant "WGPUColorWriteMask_All"))))

(defn fragment-state!
