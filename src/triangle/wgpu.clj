     (WGPUFragmentState/module (ffi/pointer shader-module))
     (WGPUFragmentState/entryPoint (ffi/string! entry-point))
     (WGPUFragmentState/targetCount 1)
     (WGPUFragmentState/targets (ffi/pointer color-target)))))

(defn- primitive-state!
