(defn- multisample-state!
  "A WGPUMultisampleState: one sample, the full 32-bit sample mask."
  []
  (doto (WGPUMultisampleState/allocate (Arena/global))
    (WGPUMultisampleState/count 1)
    (WGPUMultisampleState/mask (int -1))))

(defn render-pipeline-descriptor!
  "Build a WGPURenderPipelineDescriptor for the triangle shader. The
  vertex, primitive and multisample states live inside it by value;
  fragment points at its own struct. Automatic bind group layout:
  layout stays NULL."
  [shader-module fragment-state]
  (doto (WGPURenderPipelineDescriptor/allocate (Arena/global))
    (WGPURenderPipelineDescriptor/vertex
     (doto (WGPUVertexState/allocate (Arena/global))
         (WGPUVertexState/module (ffi/pointer shader-module))
         (WGPUVertexState/entryPoint (ffi/string! "vertex_main"))))
    (WGPURenderPipelineDescriptor/primitive (primitive-state!))
    (WGPURenderPipelineDescriptor/multisample (multisample-state!))
    (WGPURenderPipelineDescriptor/fragment (ffi/pointer fragment-state))))

(defn create-triangle-pipeline!
  "Create the render pipeline for the procedural triangle shader
  (automatic bind group layout, one B8G8R8A8UnormSrgb colour target)."
  [device shader-module]
  (wgpu_h/wgpuDeviceCreateRenderPipeline (ffi/pointer device)
                                         (render-pipeline-descriptor!
                                          shader-module
                                          (fragment-state! shader-module (color-target-state!)))))

;; ── the data-driven pipeline: vertices from a vertex buffer

(def vertex-bytes-per-vertex
  "Stride of one vertex in the vertex buffer: two floats position,
  four floats color."
  24)

(defn- vertex-attributes!
  "Build the two WGPUVertexAttribute entries: position (float32x2) at
  shader location 0, color (float32x4) at shader location 1."
  []
  (let [attributes (WGPUVertexAttribute/allocateArray 2 (Arena/global))]
    (doto (WGPUVertexAttribute/asSlice attributes 0)
          (WGPUVertexAttribute/format float32x2-vertex-format)
          (WGPUVertexAttribute/offset 0)
          (WGPUVertexAttribute/shaderLocation 0))
    (doto (WGPUVertexAttribute/asSlice attributes 1)
          (WGPUVertexAttribute/format float32x4-vertex-format)
          (WGPUVertexAttribute/offset 8)
          (WGPUVertexAttribute/shaderLocation 1))
    attributes))

(defn vertex-buffer-layout!
  "Build a WGPUVertexBufferLayout describing the interleaved 24-byte
  vertex stride. stepMode stays 0, which is Vertex."
  []
  (doto (WGPUVertexBufferLayout/allocate (Arena/global))
    (WGPUVertexBufferLayout/arrayStride (long vertex-bytes-per-vertex))
    (WGPUVertexBufferLayout/attributeCount 2)
    (WGPUVertexBufferLayout/attributes (ffi/pointer (vertex-attributes!)))))

(defn data-render-pipeline-descriptor!
  "Build a WGPURenderPipelineDescriptor for the data-driven triangle
  shader: like render-pipeline-descriptor!, but the vertex state
  names vertex_data_main and carries one vertex buffer layout."
  [shader-module fragment-state buffer-layout]
  (doto (WGPURenderPipelineDescriptor/allocate (Arena/global))
    (WGPURenderPipelineDescriptor/vertex
     (doto (WGPUVertexState/allocate (Arena/global))
         (WGPUVertexState/module (ffi/pointer shader-module))
         (WGPUVertexState/entryPoint (ffi/string! "vertex_data_main"))
         (WGPUVertexState/bufferCount 1)
         (WGPUVertexState/buffers (ffi/pointer buffer-layout))))
    (WGPURenderPipelineDescriptor/primitive (primitive-state!))
    (WGPURenderPipelineDescriptor/multisample (multisample-state!))
    (WGPURenderPipelineDescriptor/fragment (ffi/pointer fragment-state))))

(defn create-data-pipeline!
  "Create the data-driven render pipeline: a vertex buffer carries
  position and color per vertex, one B8G8R8A8UnormSrgb colour target,
  automatic bind group layout."
  [device shader-module]
  (wgpu_h/wgpuDeviceCreateRenderPipeline (ffi/pointer device)
                                         (data-render-pipeline-descriptor!
                                          shader-module
                                          (fragment-state! shader-module (color-target-state!)
                                                           "fragment_data_main")
                                          (vertex-buffer-layout!))))

(defn buffer-descriptor!
  "Build a WGPUBufferDescriptor for a buffer of the given size in
  bytes, by default with COPY_DST usage, so queue-write-buffer can
  fill it and the vertex shader can read it. Pass a different usage
  number to override."
  ([size]
   (buffer-descriptor! vertex-buffer-usage size))
  ([usage size]
   (doto (WGPUBufferDescriptor/allocate (Arena/global))
     (WGPUBufferDescriptor/usage (int usage))
     (WGPUBufferDescriptor/size (long size)))))

;; ── Clojure triangle data -> vertex floats

(defn color-component
  "Read one color component from Clojure data: integers above 1 are
  0..255 and scale down, anything else is already 0..1."
  [component]
  (if (and (integer? component) (> component 1))
    (/ (double component) 255)
    (double component)))

(defn vertex-floats
  "One vertex of Clojure data — [x y r g b], [x y r g b a] or
  [x y [r g b a]] with the color nested (alpha optional) — as the six
  floats the vertex layout wants (alpha defaults to 1)."
  [vertex]
  (let [[x y & more] vertex
        colors (if (sequential? (first more)) (first more) more)
        [r g b a] (take 4 (concat colors [1.0 1.0 1.0]))]
    [(double x) (double y)
     (color-component r) (color-component g)
     (color-component b) (color-component a)]))

(defn triangle-vertices
  "Flatten Clojure triangle data into a flat vector of floats, six per
  vertex: either a flat seq of vertices or a seq of triangles of three
  vertices each."
  [triangles]
  (->> (if (sequential? (first (first triangles)))
         (apply concat triangles)
         triangles)
       (mapcat vertex-floats)
       (into [])))

(deftest test-color-component
  (testing "integers above 1 are 0..255, everything else 0..1"
    (is (= 1.0 (color-component 255)))
    (is (= 0.0 (color-component 0)))
    (is (= 1.0 (color-component 1)))
    (is (= (/ 128.0 255) (color-component 128)))
    (is (= 0.5 (color-component 0.5)))))

(deftest test-vertex-floats
  (testing "five members pad alpha with 1, six pass through"
    (is (= [0.1 0.2 1.0 0.0 (/ 128.0 255) 1.0]
           (vertex-floats [0.1 0.2 255 0 128])))
    (is (= [0.0 0.0 1.0 0.5 0.0 0.25]
           (vertex-floats [0 0 1.0 0.5 0.0 0.25])))
    (is (= [0.5 0.5 (/ 127.0 255) (/ 127.0 255) (/ 127.0 255) 1.0]
           (vertex-floats [0.5 0.5 [127 127 127]])))))

(deftest test-triangle-vertices
  (testing "nested triangles and flat vertices flatten the same"
    (is (= (triangle-vertices [[0 0 255 0 0] [1 0 0 255 0] [0 1 0 0 255]])
           (triangle-vertices [[[0 0 255 0 0] [1 0 0 255 0] [0 1 0 0 255]]])))
    (is (= 36 (count (triangle-vertices
                      [[[0 0 255 0 0] [1 0 0 255 0] [0 1 0 0 255]]
                       [[1 1 0 0 255] [0 1 255 0 0] [1 0 0 255 0]]]))))))

;; ── per-frame plumbing

(defn- as-handle
  "A WGPU handle out of the native memory: nil for NULL, the segment
  otherwise."
  [segment]
  (when (not (.equals segment MemorySegment/NULL)) segment))

(defn acquire-swapchain-texture
  "Call wgpuSurfaceGetCurrentTexture. Returns the acquired texture
  handle (or nil if the swapchain has no free image right now), paired
  with its WGPUSurfaceTexture result buffer."
  [surface]
  (let [result (WGPUSurfaceTexture/allocate (Arena/global))]
    (wgpu_h/wgpuSurfaceGetCurrentTexture (ffi/pointer surface) result)
    [(as-handle (WGPUSurfaceTexture/texture result)) result]))

(defn render-attachment!
  "Build a WGPURenderPassColorAttachment on the given texture view:
  Clear to the demo's dark grey, Store."
  [view]
  (doto (WGPURenderPassColorAttachment/allocate (Arena/global))
    (WGPURenderPassColorAttachment/view (ffi/pointer view))
    (WGPURenderPassColorAttachment/loadOp (wgpu-constant "WGPULoadOp_Clear"))
    (WGPURenderPassColorAttachment/storeOp (wgpu-constant "WGPUStoreOp_Store"))
    (WGPURenderPassColorAttachment/clearValue
     (doto (WGPUColor/allocate (Arena/global))
         (WGPUColor/r 0.09)
         (WGPUColor/g 0.09)
         (WGPUColor/b 0.11)
         (WGPUColor/a 1.0)))))

(defn render-pass-descriptor!
  "Build a WGPURenderPassDescriptor with one colour attachment."
  [attachment]
  (doto (WGPURenderPassDescriptor/allocate (Arena/global))
    (WGPURenderPassDescriptor/colorAttachmentCount 1)
    (WGPURenderPassDescriptor/colorAttachments (ffi/pointer attachment))))

(defn draw-triangle!
  "Record and submit one frame: render pass that clears to a dark grey,
  draws three procedural vertices, then submits and presents. Releases
  everything it created; does nothing when the swapchain has no image."
  [device queue surface pipeline]
  (let [[texture _] (acquire-swapchain-texture surface)]
    (when texture
      (let [view (wgpu_h/wgpuTextureCreateView texture null)
            encoder (wgpu_h/wgpuDeviceCreateCommandEncoder (ffi/pointer device) null)
            pass (wgpu_h/wgpuCommandEncoderBeginRenderPass encoder
                                                           (render-pass-descriptor! (render-attachment! view)))
            _ (wgpu_h/wgpuRenderPassEncoderSetPipeline pass (ffi/pointer pipeline))
            _ (wgpu_h/wgpuRenderPassEncoderDraw pass 3 1 0 0)
            _ (wgpu_h/wgpuRenderPassEncoderEnd pass)
            _ (wgpu_h/wgpuRenderPassEncoderRelease pass)
            command-buffer (wgpu_h/wgpuCommandEncoderFinish encoder null)
            commands (doto (ffi/pointer-array! 1)
                       (ffi/write-pointer! 0 command-buffer))]
        (wgpu_h/wgpuQueueSubmit (ffi/pointer queue) 1 commands)
        (wgpu_h/wgpuSurfacePresent (ffi/pointer surface))
        (wgpu_h/wgpuCommandBufferRelease command-buffer)
        (wgpu_h/wgpuCommandEncoderRelease encoder)
        (wgpu_h/wgpuTextureViewRelease view)
        (wgpu_h/wgpuTextureRelease texture)))))

(defn vertex-data!
  "Copy the flat vertex floats (triangle-vertices) into freshly
  allocated native memory, four bytes each; returns the segment."
  [floats]
  (let [data (ffi/allocate! (* 4 (count floats)))]
    (doseq [[index float-value] (map-indexed vector floats)]
      (ffi/write-f32! data (* 4 index) float-value))
    data))

(defn draw-triangles!
  "Draw the given Clojure triangle data (triangle-vertices) as one
  frame with the data-driven pipeline: the vertices upload into a
  fresh vertex buffer, a render pass clears and draws them, the frame
  presents, everything releases. Positions are clip-space (x right,
  y up, -1..1); a vertex count that is not a multiple of three throws."
  [device queue surface pipeline triangles]
  (let [floats (triangle-vertices triangles)
        vertex-count (quot (count floats) 6)]
    (when-not (zero? (rem vertex-count 3))
      (throw (ex-info "triangle data must hold a multiple of three vertices"
                      {:vertex-count vertex-count})))
    (let [data (vertex-data! floats)
          data-bytes (long (* 4 (count floats)))
          buffer (wgpu_h/wgpuDeviceCreateBuffer (ffi/pointer device)
                                                (buffer-descriptor! data-bytes))]
      (wgpu_h/wgpuQueueWriteBuffer (ffi/pointer queue) buffer 0 data data-bytes)
      (let [[texture _] (acquire-swapchain-texture surface)]
        (when texture
          (let [view (wgpu_h/wgpuTextureCreateView texture null)
                encoder (wgpu_h/wgpuDeviceCreateCommandEncoder (ffi/pointer device) null)
                pass (wgpu_h/wgpuCommandEncoderBeginRenderPass encoder
                                                               (render-pass-descriptor! (render-attachment! view)))]
            (wgpu_h/wgpuRenderPassEncoderSetPipeline pass (ffi/pointer pipeline))
            (wgpu_h/wgpuRenderPassEncoderSetVertexBuffer pass 0 buffer 0 data-bytes)
            (wgpu_h/wgpuRenderPassEncoderDraw pass (int vertex-count) 1 0 0)
            (wgpu_h/wgpuRenderPassEncoderEnd pass)
